#!/usr/bin/env python3
# Writes Sources/SSHIdentity/BlowfishTables.swift: Blowfish's initial state,
# the fractional hex digits of pi, computed with exact integer arithmetic.
# Usage: python3 -I Scripts/gen-blowfish-tables.py > Sources/SSHIdentity/BlowfishTables.swift
WORDS = 18 + 4 * 256
bits = WORDS * 32 + 128
one = 1 << bits
def atan_inv(x):
    total, term, n, sign = 0, one // x, 1, 1
    x2 = x * x
    while term:
        total += sign * (term // n)
        term //= x2; n += 2; sign = -sign
    return total
pi = 16 * atan_inv(5) - 4 * atan_inv(239)
frac = pi - (3 << bits)
words = [(frac >> (bits - 32 * (i + 1))) & 0xFFFFFFFF for i in range(WORDS)]
assert words[0] == 0x243F6A88 and words[17] == 0x8979FB1B, hex(words[17])
assert words[18] == 0xD1310BA6 and words[-1] == 0x3AC372E6, hex(words[-1])
def emit(name, ws, doc):
    out = [f"  /// {doc}", f"  static let {name}: [UInt32] = ["]
    for i in range(0, len(ws), 6):
        out.append("    " + ", ".join(f"0x{w:08X}" for w in ws[i:i+6]) + ",")
    out.append("  ]")
    return "\n".join(out)
print("// Generated by Scripts/gen-blowfish-tables.py: the fractional hex digits")
print("// of pi, as Blowfish's initial state is defined. Do not edit.")
print()
print("extension Blowfish {")
print(emit("initialP", words[:18], "Initial P-array: digits 1–144."))
print()
print(emit("initialS", words[18:], "Initial S-boxes S0–S3, 256 words each, following P."))
print("}")
